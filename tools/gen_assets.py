"""Regenerates the embedded assets of the KDX-style UI (run from the repo root).

    python tools/gen_assets.py          fonts.css + icons.js

Outputs are committed: the build itself never runs Python.
  assets/fonts.css  Archivo + Overpass Mono (latin subsets, OFL) as base64 @font-face
  assets/icons.js   the pixel icons of tools/pixel_icons.py as SVG strings
"""
import base64
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import pixel_icons  # noqa: E402

RANGE = ("U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, "
         "U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD")


def b64(path):
    return base64.b64encode(path.read_bytes()).decode()


def fonts_css():
    f = root / 'third_party' / 'fonts'
    return (
        "/* Generated by tools/gen_assets.py -- Archivo (wght 500-800, wdth 62-125) and Overpass Mono\n"
        "   (wght 500-700), latin subsets, SIL OFL 1.1 (licenses in third_party/fonts). */\n"
        "@font-face { font-family: 'Archivo'; font-style: normal; font-weight: 500 800; font-stretch: 62% 125%;\n"
        f"  src: url(data:font/woff2;base64,{b64(f / 'archivo-latin.woff2')}) format('woff2'); unicode-range: {RANGE}; }}\n"
        "@font-face { font-family: 'Overpass Mono'; font-style: normal; font-weight: 500 700;\n"
        f"  src: url(data:font/woff2;base64,{b64(f / 'overpass-latin.woff2')}) format('woff2'); unicode-range: {RANGE}; }}\n")


def icons_js():
    out = ["// Generated by tools/gen_assets.py from tools/pixel_icons.py -- do not edit.",
           "// 16x16 pixel icons, SVG strings. pix(name, size) -> markup; fillPix() fills every [data-ic].",
           "const PIX = {"]
    for name, svg in pixel_icons.all_svgs().items():
        out.append(f"  {name}: '{svg}',")
    out.append("};")
    out.append('''const pix = (name, size = 16) =>
  (PIX[name] || PIX.enceinte).replace('width="16" height="16"', `width="${size}" height="${size}"`);
const fillPix = (scope = document) => scope.querySelectorAll("[data-ic]").forEach(el => {
  el.innerHTML = pix(el.dataset.ic, +el.dataset.size || 16);
});
''')
    return "\n".join(out)


(root / 'assets' / 'fonts.css').write_text(fonts_css(), encoding='utf-8')
(root / 'assets' / 'icons.js').write_text(icons_js(), encoding='utf-8')
for n in ('fonts.css', 'icons.js'):
    print(n, (root / 'assets' / n).stat().st_size)
