"""Regenerates the embedded assets of the KDX-style UI (run from the repo root).

    python tools/gen_assets.py          fonts.css + icons.js
    python tools/gen_assets.py --lava   also re-renders the wallpaper (needs Chrome + Pillow)

Outputs are committed: the build itself never runs Python.
  assets/fonts.css  Archivo + Overpass Mono (latin subsets, OFL) as base64 @font-face
  assets/icons.js   the pixel icons of tools/pixel_icons.py as SVG strings
  assets/lava.css   the red "lava" wallpaper as a base64 JPEG custom property
"""
import base64
import io
import subprocess
import sys
import tempfile
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import pixel_icons  # noqa: E402

RANGE = ("U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, "
         "U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD")


def b64(path):
    return base64.b64encode(path.read_bytes()).decode()


def fonts_css():
    f = root / 'third_party' / 'fonts'
    return (
        "/* Generated by tools/gen_assets.py -- Archivo (wght 500-800, wdth 62-125) and Overpass Mono\n"
        "   (wght 500-700), latin subsets, SIL OFL 1.1 (licenses in third_party/fonts). */\n"
        "@font-face { font-family: 'Archivo'; font-style: normal; font-weight: 500 800; font-stretch: 62% 125%;\n"
        f"  src: url(data:font/woff2;base64,{b64(f / 'archivo-latin.woff2')}) format('woff2'); unicode-range: {RANGE}; }}\n"
        "@font-face { font-family: 'Overpass Mono'; font-style: normal; font-weight: 500 700;\n"
        f"  src: url(data:font/woff2;base64,{b64(f / 'overpass-latin.woff2')}) format('woff2'); unicode-range: {RANGE}; }}\n")


def icons_js():
    out = ["// Generated by tools/gen_assets.py from tools/pixel_icons.py -- do not edit.",
           "// 16x16 pixel icons, SVG strings. pix(name, size) -> markup; fillPix() fills every [data-ic].",
           "const PIX = {"]
    for name, svg in pixel_icons.all_svgs().items():
        out.append(f"  {name}: '{svg}',")
    out.append("};")
    out.append('''const pix = (name, size = 16) =>
  (PIX[name] || PIX.enceinte).replace('width="16" height="16"', `width="${size}" height="${size}"`);
const fillPix = (scope = document) => scope.querySelectorAll("[data-ic]").forEach(el => {
  el.innerHTML = pix(el.dataset.ic, +el.dataset.size || 16);
});
''')
    return "\n".join(out)


LAVA_SVG = '''<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="800"><defs>
<filter id="l" x="0" y="0" width="100%" height="100%" color-interpolation-filters="sRGB">
<feTurbulence type="fractalNoise" baseFrequency="0.0035 0.0065" numOctaves="5" seed="11" result="n"/>
<feComponentTransfer in="n">
<feFuncR type="table" tableValues="0.03 0.22 0.55 0.84 1"/>
<feFuncG type="table" tableValues="0 0 0.01 0.08 0.38"/>
<feFuncB type="table" tableValues="0 0 0 0.01 0.05"/>
<feFuncA type="table" tableValues="1 1"/></feComponentTransfer></filter></defs>
<rect width="1280" height="800" fill="#000" filter="url(#l)"/><rect width="1280" height="800" fill="#000" opacity="0.2"/></svg>'''


def lava_css():
    from PIL import Image
    chrome = r'C:\Program Files\Google\Chrome\Application\chrome.exe'
    with tempfile.TemporaryDirectory() as d:
        svg, png = Path(d) / 'lava.svg', Path(d) / 'lava.png'
        svg.write_text(LAVA_SVG, encoding='utf-8')
        subprocess.run([chrome, '--headless=new', '--disable-gpu', '--hide-scrollbars', '--window-size=1280,800',
                        f'--screenshot={png}', svg.as_uri()], check=True, capture_output=True, timeout=90)
        buf = io.BytesIO()
        Image.open(png).convert('RGB').save(buf, 'JPEG', quality=72, optimize=True)
    return ("/* Generated by tools/gen_assets.py --lava: the red wallpaper seen between the panels. */\n"
            f":root {{ --lava: url(data:image/jpeg;base64,{base64.b64encode(buf.getvalue()).decode()}); }}\n")


(root / 'assets' / 'fonts.css').write_text(fonts_css(), encoding='utf-8')
(root / 'assets' / 'icons.js').write_text(icons_js(), encoding='utf-8')
if '--lava' in sys.argv or not (root / 'assets' / 'lava.css').exists():
    (root / 'assets' / 'lava.css').write_text(lava_css(), encoding='utf-8')
for n in ('fonts.css', 'icons.js', 'lava.css'):
    print(n, (root / 'assets' / n).stat().st_size)
